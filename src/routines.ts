import type { Config, DeviceConfig } from "./config.ts";

type Step = { device: DeviceConfig; on: boolean };
type Automation = { phrases: string[]; steps: Step[] };

/**
 * Builds a Google Home script-editor automation (YAML) from the config: one automation per
 * device phrase list (`phrases.on` / `phrases.off`) and one per entry in `routines`.
 * Paste it at home.google.com → Automations → Add new → Script editor.
 */
export function generateRoutines(config: Config, opts: { title?: string } = {}): string {
    const byName = new Map(config.devices.map(d => [d.name.toLowerCase(), d]));
    const automations: Automation[] = [];
    for (const device of config.devices) {
        if (device.phrases?.on?.length) automations.push({ phrases: device.phrases.on, steps: [{ device, on: true }] });
        if (device.phrases?.off?.length) automations.push({ phrases: device.phrases.off, steps: [{ device, on: false }] });
    }
    for (const r of config.routines) {
        const steps = r.actions.flatMap(step =>
            Object.entries(step).map(([name, on]) => ({ device: byName.get(name.toLowerCase())!, on })),
        );
        automations.push({ phrases: r.phrases, steps });
    }

    const q = (s: string) => (/^[\w åäöÅÄÖéü'-]+$/.test(s) && !/^(true|false|yes|no|on|off|null)$/i.test(s) ? s : JSON.stringify(s));
    const out: string[] = [
        "# Generated by `archnest routines` from your archnest config.",
        `# Needs every archnest device in the Google Home room "${config.room}".`,
        "metadata:",
        `  name: ${q(opts.title ?? config.name)}`,
        `  description: ${q(`Voice commands for this computer, generated by archnest`)}`,
        "",
        "automations:",
    ];
    for (const a of automations) {
        out.push("  - starters:");
        for (const p of a.phrases) {
            out.push("      - type: assistant.event.OkGoogle", "        eventData: query", `        is: ${q(p.toLowerCase())}`);
        }
        out.push("    actions:");
        for (const { device, on } of a.steps) {
            const ref = q(`${device.name} - ${config.room}`);
            if (device.type === "lock") {
                // Unlocking by routine is refused by archnest anyway; only emit locking.
                if (on) out.push("      - type: device.command.LockUnlock", `        devices: ${ref}`, "        lock: true");
            } else {
                out.push("      - type: device.command.OnOff", `        devices: ${ref}`, `        on: ${on}`);
            }
        }
        out.push("");
    }
    if (!automations.length) out.push("  []  # no `phrases` or `routines` in the config yet");
    return `${out.join("\n").trimEnd()}\n`;
}
